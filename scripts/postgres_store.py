"""
Writes drivine/backend/postgres/postgres_store_text.py from drivine4j's store: the block that makes a Postgres graph,
its tables, functions and version, so that drivine-python makes the store drivine4j and TypeScript's Drivine make, byte
for byte, and a graph written from the JVM, from Node and from Python is one. TypeScript's scripts/postgres-store.js,
ported.

Give it the text of drivine4j's `PostgresGraph("zzgraphzz").ensuring` and `PostgresGraph.VERSION`, each in a file:

    uv run python scripts/postgres_store.py ensuring.sql version.txt

Run it again whenever drivine4j's store changes: its version says when it has.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "drivine" / "backend" / "postgres" / "postgres_store_text.py"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument("ensuring", type=Path, help="drivine4j's PostgresGraph('zzgraphzz').ensuring")
    parser.add_argument("version", type=Path, help="drivine4j's PostgresGraph.VERSION")
    args = parser.parse_args()
    ensuring = args.ensuring.read_text(encoding="utf-8")
    version = args.version.read_text(encoding="utf-8").strip()
    lines = "\n".join(f"        {json.dumps(it, ensure_ascii=False)}," for it in ensuring.split("\n"))
    TARGET.write_text(
        f'''# Generated by scripts/postgres_store.py from drivine4j's PostgresGraph: do not edit.
"""drivine4j's block that makes a Postgres graph's store, as TypeScript's Drivine holds it too."""

POSTGRES_STORE_VERSION = {json.dumps(version)}
"""The version of drivine4j's store this block makes: the node table's comment says which made a store."""

GRAPH_PLACEHOLDER = "zzgraphzz"
"""What stands for the graph's name in the block."""

POSTGRES_STORE_ENSURING = "\\n".join(
    [
{lines}
    ]
)
"""drivine4j's block that makes a graph's store, its name written as GRAPH_PLACEHOLDER."""
''',
        encoding="utf-8",
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", str(TARGET)], check=True, cwd=ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
